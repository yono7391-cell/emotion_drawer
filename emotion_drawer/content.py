def with_object_particle(word: str) -> str:
    """'서운함'을 / '감사'를 처럼 받침에 맞는 조사를 붙여 따옴표로 감싼다."""
    last = word[-1] if word else ""
    has_final = "가" <= last <= "힣" and (ord(last) - 0xAC00) % 28 != 0
    return f"'{word}'{'을' if has_final else '를'}"


